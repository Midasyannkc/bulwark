"""Run every Bulwark module and write out/report.json and docs/REPORT.md.  Deterministic, no clocks."""
import copy, json
from collections import Counter
from datetime import date
from pathlib import Path

from bulwark import refs
from bulwark.evidence import package as P
from bulwark.fhir import api, deid, integration, spec
from bulwark.ir import runbook as RB, tabletop as TT
from bulwark.threatmodel import engine as TM

ROOT = Path(__file__).resolve().parents[1]


def threat():
    m = TM.load(ROOT / "data/model/cloudclinic.yml")
    f = TM.analyze(m)
    worse = copy.deepcopy(m)
    for fl in worse["flows"]: fl["tls"] = False
    for e in worse["elements"].values():
        if e["kind"] == "store": e["encrypted_at_rest"] = False
    w = TM.analyze(worse)
    return {"elements": len(m["elements"]), "flows": len(m["flows"]), "threats": len(f), "by_stride": dict(sorted(Counter(x.refs["stride"] for x in f).items())),
            "by_severity": dict(sorted(Counter(x.severity for x in f).items())), "threat_list": [f"{x.rule} @ {x.location}" for x in f],
            "attack_techniques_cited": sorted({x.refs["attack"] for x in f + w}), "nist_controls_cited": sorted({c for x in f + w for c in x.refs["nist"]}),
            "citations_unverified": len(TM.validate_refs(f + w)), "what_if_no_tls_no_encryption_threats": len(w)}


def ir():
    doc = RB.load(ROOT / "data/ir/runbooks.yml")
    sc = TT.load(ROOT / "data/ir/scenarios.yml")["scenarios"][0]
    rb = next(r for r in doc["runbooks"] if r["id"] == sc["runbook"])
    strong, weak = TT.score(sc, rb, sc["plays"]["strong"]), TT.score(sc, rb, sc["plays"]["weak"])
    return {"runbooks": len(doc["runbooks"]), "lint_findings": len(RB.lint(doc)), "tabletop": sc["id"],
            "strong_grade": strong["grade"], "weak_grade": weak["grade"], "weak_findings": len(weak["findings"]), "breach_deadlines": strong["deadlines"]}


def evidence():
    snap = json.loads((ROOT / "data/snapshots/cloud_2026-10-30.json").read_text())
    pkg = P.build(snap)
    st = Counter(i["status"] for i in pkg["items"])
    return {"as_of": pkg["as_of"], "controls": len(pkg["items"]), "status": dict(sorted(st.items())),
            "exceptions": {i["control"]: i["exceptions"] for i in pkg["items"] if i["exceptions"]}, "hash_failures": len(P.verify_hashes(pkg)),
            "nist_mapping_errors": len(P.mapping_errors()), "baseline_coverage": P.coverage(), "stale_after_60_days": len(P.stale(pkg, date(2026, 12, 29)))}


def fhir():
    fx = json.loads((ROOT / "data/fhir/fixtures.json").read_text())
    allr = fx["patients"] + fx["observations"] + fx["encounters"]
    key, names = b"report-key", deid.names_for(fx["patients"])
    raw = ["Ada", "Fakename", "Samplesmith", "Ben", "Cora", "555-010-0101", "900-12-3456", "MRN-100234", "12 Imaginary Rd", "1948-03-14"]
    leaks = sum(len(deid.leaks(deid.deidentify(r, key, names=names), raw)) for r in allr)
    snap = copy.deepcopy(api.STORE); api.AUDIT.clear()
    p1 = {"scope": "patient/*.read patient/Observation.write", "patient": "p1", "sub": "pt-1"}
    h = lambda method, path, tok=p1, q=None, b=None: api.handle({"method": method, "path": path, "query": q or {}, "token": tok, "body": b})[0]
    probes = {"read another patient's record": h("GET", "/Patient/p2"), "export without token": h("GET", "/$export", None), "export with patient token": h("GET", "/$export"),
              "write into another compartment": h("POST", "/Observation", b={"resourceType": "Observation", "id": "o8", "status": "final", "code": {"text": "x"}, "subject": {"reference": "Patient/p2"}}),
              "read own record (must work)": h("GET", "/Patient/p1")}
    api.handle({"method": "GET", "path": "/Patient", "query": {"name": "Samplesmith"}, "token": p1})
    phi_in_log = "Samplesmith" in json.dumps(api.AUDIT)
    api.STORE.clear(); api.STORE.update(snap)
    parts = integration.load()
    return {"fixtures_validated_against_r4": len(allr), "spec_findings": sum(len(spec.validate(r)) for r in allr), "r4_resources_loaded": len(refs.fhir()),
            "deid_leaks": leaks, "api_probe_status": probes, "phi_in_audit_log": phi_in_log,
            "partners": {p["id"]: len(integration.assess(p)) for p in parts}}


def build():
    notes = json.loads((ROOT / "docs/incident_notes.json").read_text())
    return {"threat_model": threat(), "incident_response": ir(), "evidence": evidence(), "fhir": fhir(), "incidents": len(notes),
            "reference_data": {"nist_controls": len(refs.nist()["controls"]), "nist_moderate_baseline": len(refs.nist()["moderate_baseline"]), "attack_techniques": len(refs.attack())}}


def markdown(r):
    t, i, e, f = r["threat_model"], r["incident_response"], r["evidence"], r["fhir"]
    L = ["# Bulwark report", "", "Generated by `python -m bulwark`; no timestamps.", "", "## Threat model", "",
         f"- {t['elements']} elements, {t['flows']} flows, {t['threats']} threats: STRIDE {t['by_stride']}, severity {t['by_severity']}",
         f"- Threats: {', '.join(t['threat_list'])}", f"- ATT&CK techniques cited: {', '.join(t['attack_techniques_cited'])}; unverified citations: {t['citations_unverified']}",
         f"- NIST controls cited: {', '.join(t['nist_controls_cited'])}", f"- What-if (no TLS, no encryption at rest): {t['what_if_no_tls_no_encryption_threats']} threats", "",
         "## Incident response", "",
         f"- {i['runbooks']} runbooks, {i['lint_findings']} lint findings. Tabletop {i['tabletop']}: strong play {i['strong_grade']}, weak play {i['weak_grade']} with {i['weak_findings']} findings.",
         f"- Breach notification deadlines from the discovery date: {i['breach_deadlines']}", "",
         "## Evidence", "",
         f"- As of {e['as_of']}: {e['controls']} controls, status {e['status']}; hash failures {e['hash_failures']}; NIST mapping errors {e['nist_mapping_errors']}",
         f"- Exceptions: {e['exceptions']}",
         f"- Coverage of the real NIST 800-53 Moderate baseline (base controls): {e['baseline_coverage']['covered']} of {e['baseline_coverage']['baseline_base_controls']} ({e['baseline_coverage']['percent']} percent). Partial on purpose.", "",
         "## FHIR and integrations", "",
         f"- {f['fixtures_validated_against_r4']} fixtures validated against {f['r4_resources_loaded']} real R4 resource definitions, {f['spec_findings']} findings; de-identification leaks: {f['deid_leaks']}",
         f"- API probes (HTTP status): {f['api_probe_status']}; PHI in audit log: {f['phi_in_audit_log']}",
         f"- Partner assessment findings: {f['partners']}", "", "## Incidents", "", f"{r['incidents']} incidents with reproduce and fix commits; see docs/incidents.md.", ""]
    return "\n".join(L)


def main():
    r = build()
    (ROOT / "out").mkdir(exist_ok=True)
    (ROOT / "out/report.json").write_text(json.dumps(r, indent=1, sort_keys=True) + "\n")
    (ROOT / "docs/REPORT.md").write_text(markdown(r))
    print(markdown(r))
